export type Key = keyof (typeof dict)['es']

export function translate(lang: Lang, key: Key): string {
  return dict[lang][key]
}

export function detectLang(nav: Pick<Navigator, 'language'> = navigator): Lang {
  return nav.language.toLowerCase().startsWith('es') ? 'es' : 'en'
}

/** Keys present in one language but not in the other: both lists must stay empty. */
export function missingKeys(): { es: string[]; en: string[] } {
  const es = Object.keys(dict.es)
  const en = Object.keys(dict.en)
  return { es: en.filter((k) => !(k in dict.es)), en: es.filter((k) => !(k in dict.en)) }
}
