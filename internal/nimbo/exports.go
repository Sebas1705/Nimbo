package nimbo

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// ExportAWSEndpoint is where the AWS emulator answers.
const ExportAWSEndpoint = "http://localhost:4566"

var exportAWSServices = []string{
	"apigateway", "cloudwatch", "cloudwatchlogs", "dynamodb", "eventbridge", "iam", "kinesis",
	"kms", "lambda", "s3", "secretsmanager", "sfn", "sns", "sqs", "ssm", "sts",
}

// ExportAWSEndpointFor is the endpoint of the AWS emulator, optionally through its Toxiproxy port.
func ExportAWSEndpointFor(chaos bool) string {
	if chaos {
		return fmt.Sprintf("http://localhost:%d", coreChaosTargetByID("floci-aws").proxyPort)
	}
	return ExportAWSEndpoint
}

var exportLocalhostPort = regexp.MustCompile(`localhost:(\d+)`)

// ExportViaChaos rewrites `localhost:<emulator port>` to the matching Toxiproxy port; endpoints without a proxy are
// left alone.
func ExportViaChaos(value string) string {
	return exportLocalhostPort.ReplaceAllStringFunc(value, func(m string) string {
		port, _ := strconv.Atoi(exportLocalhostPort.FindStringSubmatch(m)[1])
		for _, t := range coreChaosTargets {
			if t.upstreamPort == port {
				return fmt.Sprintf("localhost:%d", t.proxyPort)
			}
		}
		return m
	})
}

// ExportEnv groups the endpoints of the providers per provider, as a .env file.
func ExportEnv(defs []ProviderDef, chaos bool) string {
	var blocks []string
	for _, def := range defs {
		if len(def.Endpoints) == 0 {
			continue
		}
		lines := make([]string, 0, len(def.Endpoints))
		for _, kv := range def.Endpoints {
			v := kv.Value
			if chaos {
				v = ExportViaChaos(v)
			}
			lines = append(lines, kv.Key+"="+v)
		}
		blocks = append(blocks, "# "+def.Name+"\n"+strings.Join(lines, "\n"))
	}
	prefix := ""
	if chaos {
		prefix = "# Through Toxiproxy: start it and apply faults in the Chaos tab\n"
	}
	return prefix + strings.Join(blocks, "\n\n")
}

// ExportTofuAwsOverride: `*_override.tf` files are merged over the matching provider block by Terraform and OpenTofu.
func ExportTofuAwsOverride(chaos bool) string {
	var b strings.Builder
	b.WriteString("# Generated by Nimbo. Drop next to your .tf files; remove it to go back to real AWS.\n")
	b.WriteString("provider \"aws\" {\n")
	b.WriteString("  region                      = \"us-east-1\"\n")
	b.WriteString("  access_key                  = \"test\"\n")
	b.WriteString("  secret_key                  = \"test\"\n")
	b.WriteString("  s3_use_path_style           = true\n")
	b.WriteString("  skip_credentials_validation = true\n")
	b.WriteString("  skip_metadata_api_check     = true\n")
	b.WriteString("  skip_requesting_account_id  = true\n")
	b.WriteString("\n")
	b.WriteString("  endpoints {\n")
	width := 0
	for _, s := range exportAWSServices {
		if len(s) > width {
			width = len(s)
		}
	}
	endpoint := ExportAWSEndpointFor(chaos)
	for _, s := range exportAWSServices {
		fmt.Fprintf(&b, "    %-*s = \"%s\"\n", width, s, endpoint)
	}
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

func ExportAwsCliProfile(chaos bool) string {
	return "# Add to ~/.aws/config, then use: aws --profile nimbo s3 ls\n" +
		"[profile nimbo]\n" +
		"region = us-east-1\n" +
		"endpoint_url = " + ExportAWSEndpointFor(chaos) + "\n" +
		"aws_access_key_id = test\n" +
		"aws_secret_access_key = test\n"
}

// ExportFormat is one kind of file Nimbo can write for a stack. NeedsAWS formats only make sense with floci-aws.
type ExportFormat struct {
	ID, Filename string
	NeedsAWS     bool
}

var (
	ExportFormatEnv        = ExportFormat{"env", "nimbo.env", false}
	ExportFormatCompose    = ExportFormat{"compose", "docker-compose.yml", false}
	ExportFormatComposeEnv = ExportFormat{"composeenv", ".env", false}
	ExportFormatSpring     = ExportFormat{"spring", "application-nimbo.yml", false}
	ExportFormatDotnet     = ExportFormat{"dotnet", "appsettings.Nimbo.json", false}
	ExportFormatTofu       = ExportFormat{"tofu", "nimbo_override.tf", true}
	ExportFormatAwsCli     = ExportFormat{"awscli", "aws-config-nimbo.ini", true}
)

var exportFormats = []ExportFormat{ExportFormatEnv, ExportFormatCompose, ExportFormatComposeEnv, ExportFormatSpring, ExportFormatDotnet, ExportFormatTofu, ExportFormatAwsCli}

// ExportFormatOf finds a format by its id.
func ExportFormatOf(id string) (ExportFormat, bool) {
	for _, f := range exportFormats {
		if f.ID == id {
			return f, true
		}
	}
	return ExportFormat{}, false
}
