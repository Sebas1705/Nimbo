package es.sebas1705.nimbo

/** Generates the client-side configuration needed to point real tooling at the local emulators. */
object Exports {
    const val AWS_ENDPOINT = "http://localhost:4566"

    private val awsServices = listOf(
        "apigateway", "cloudwatch", "cloudwatchlogs", "dynamodb", "eventbridge", "iam", "kinesis",
        "kms", "lambda", "s3", "secretsmanager", "sfn", "sns", "sqs", "ssm", "sts",
    )

    fun env(defs: List<ProviderDef>): String = defs
        .filter { it.endpoints.isNotEmpty() }
        .joinToString("\n\n") { def ->
            "# ${def.name}\n" + def.endpoints.entries.joinToString("\n") { "${it.key}=${it.value}" }
        }

    /** `*_override.tf` files are merged over the matching provider block by Terraform and OpenTofu. */
    fun tofuAwsOverride(): String = buildString {
        appendLine("# Generated by Nimbo. Drop next to your .tf files; remove it to go back to real AWS.")
        appendLine("provider \"aws\" {")
        appendLine("  region                      = \"us-east-1\"")
        appendLine("  access_key                  = \"test\"")
        appendLine("  secret_key                  = \"test\"")
        appendLine("  s3_use_path_style           = true")
        appendLine("  skip_credentials_validation = true")
        appendLine("  skip_metadata_api_check     = true")
        appendLine("  skip_requesting_account_id  = true")
        appendLine()
        appendLine("  endpoints {")
        val width = awsServices.maxOf { it.length }
        awsServices.forEach { appendLine("    ${it.padEnd(width)} = \"$AWS_ENDPOINT\"") }
        appendLine("  }")
        appendLine("}")
    }

    fun awsCliProfile(): String = """
        # Add to ~/.aws/config, then use: aws --profile nimbo s3 ls
        [profile nimbo]
        region = us-east-1
        endpoint_url = $AWS_ENDPOINT
        aws_access_key_id = test
        aws_secret_access_key = test
    """.trimIndent() + "\n"
}

enum class ExportFormat(val id: String, val filename: String) {
    ENV("env", "nimbo.env"),
    TOFU("tofu", "nimbo_override.tf"),
    AWS_CLI("awscli", "aws-config-nimbo.ini");

    companion object {
        fun of(id: String?): ExportFormat? = entries.firstOrNull { it.id == id }
    }
}
